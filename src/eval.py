from collections import Counter
import numpy as np
import re
import string

from evaluate import load  # type: ignore
from rouge_score import rouge_scorer, scoring  # type: ignore
from typing import List, Mapping

metric_bertscore = load("bertscore")  # type: ignore
metric_sari = load("sari")  # type: ignore
metric_meteor = load("meteor")  # type: ignore
metric_bleu = load("bleu")  # type: ignore
metric_chrf = load("chrf")  # type: ignore


def calculate_bleu(predictions: List[str], references: List[List[str]]):
    try:
        results_bleu = metric_bleu.compute(predictions=predictions, references=references)  # type: ignore
    except ZeroDivisionError:
        return 0.0
    if results_bleu:
        return float(results_bleu["bleu"])  # type: ignore
    else:
        raise ValueError("Error in computing BLEU")


def calculate_chrf(predictions: List[str], references: List[List[str]]):
    return float(metric_chrf.compute(predictions=predictions, references=references)["score"])  # type: ignore


def calculate_meteor(predictions: List[str], references: List[List[str]]):
    results_meteor = metric_meteor.compute(  # type: ignore
        predictions=predictions, references=references
    )
    if results_meteor:
        return float(results_meteor["meteor"])  # type: ignore
    else:
        raise ValueError("Error in computing METEOR")


def calculate_rouge(
    predictions: List[str],
    references: List[List[str]],
):
    """Calculate rouge using rouge_scorer package.
    Args:
        pred_lns: list of summaries generated by model
        tgt_lns: list of groundtruth summaries (e.g. contents of val.target)
    Returns:
         Dict[score: value] if aggregate else defaultdict(list) keyed by rouge_keys
    """
    scorer = rouge_scorer.RougeScorer(
        ["rouge1", "rouge2", "rougeL", "rougeLsum"], use_stemmer=True
    )
    aggregator = scoring.BootstrapAggregator()
    for pred, tgt in zip(predictions, references):
        scores = scorer.score_multi(tgt, pred)  # type: ignore
        aggregator.add_scores(scores)  # type: ignore

    result = aggregator.aggregate()  # type: ignore
    return {str(k): float(v.mid.fmeasure * 100) for k, v in result.items()}  # type: ignore


def calculate_bertscore(predictions: List[str], references: List[List[str]]):
    result_bert = list[float]()
    for pred, label in zip(predictions, references):
        bertscore_dict = metric_bertscore.compute(  # type: ignore
            predictions=[pred] * len(label), references=label, lang="en"
        )
        if bertscore_dict:
            if isinstance(bertscore_dict["f1"], list):
                result_bert.append(float(bertscore_dict["f1"][0]))  # type: ignore
            else:
                result_bert.append(float(bertscore_dict["f1"]))  # type: ignore

    return float(np.mean(result_bert))


def calculate_sari(
    sources: List[str], predictions: List[str], references: List[List[str]]
):
    sari_result_dict = metric_sari.compute(  # type: ignore
        sources=sources or [],
        predictions=predictions or [],
        references=references or [],
    )
    return float(sari_result_dict["sari"])  # type: ignore


def normalize_answer(s: str):
    """Lower text and remove punctuation, articles and extra whitespace."""

    def remove_articles(text: str):
        return re.sub(r"\b(a|an|the)\b", " ", text)

    def white_space_fix(text: str):
        return " ".join(text.split())

    def remove_punc(text: str):
        exclude = set(string.punctuation)
        return "".join(ch for ch in text if ch not in exclude)

    def lower(text: str):
        return text.lower()

    return white_space_fix(remove_articles(remove_punc(lower(s))))


def calculate_f1_indiv(prediction: str, ground_truth: str):
    prediction_tokens = normalize_answer(prediction).split()
    ground_truth_tokens = normalize_answer(ground_truth).split()
    common = Counter(prediction_tokens) & Counter(ground_truth_tokens)
    num_same = sum(common.values())
    if num_same == 0:
        return 0
    precision = 1.0 * num_same / len(prediction_tokens)
    recall = 1.0 * num_same / len(ground_truth_tokens)
    f1 = (2 * precision * recall) / (precision + recall)
    return f1


def calculate_exact_match_gsm8k(predictions: List[str], references: List[List[str]]):

    def extract_gsm8k_answer(s: str):
        return s.split("####")[-1].strip().lower()

    answers = [extract_gsm8k_answer(lst[0]) for lst in references]
    predictions = [extract_gsm8k_answer(pred) for pred in predictions]
    return sum([a == p for (a, p) in zip(answers, predictions)]) / len(predictions)


def calculate_exact_match_math(predictions: List[str], references: List[List[str]]):

    def extract_boxed(text: str):
        results = []
        i = 0
        while i < len(text):
            if text.startswith(r"\boxed{", i):
                i += len(r"\boxed{")
                depth = 1
                start = i
                while i < len(text) and depth > 0:
                    if text[i] == "{":
                        depth += 1
                    elif text[i] == "}":
                        depth -= 1
                    i += 1
                results.append(text[start : i - 1])  # exclude closing brace
            else:
                i += 1
        if results:
            return results[0]
        return "None"

    answers = [extract_boxed(lst[0]) for lst in references]
    predictions = [extract_boxed(pred) for pred in predictions]
    return sum([a == p for (a, p) in zip(answers, predictions)]) / len(predictions)


def calculate_f1(predictions: List[str], references: List[List[str]]):
    scores = [calculate_f1_indiv(p, r[0]) for (p, r) in zip(predictions, references)]
    return float(np.array(scores).mean())


def clean_string(s: str):
    s = s.replace("-lrb-", " ").replace("-rrb-", " ")
    s = s.replace("<s>", "").replace("</s>", "").replace("<pad>", "")
    return re.sub(" +", " ", s)


def compute_metrics(
    sources: List[str],
    predictions: List[str],
    labels: List[List[str]],
    metrics: List[str],
):
    """Test docstring.

    Args:
        sources (list[str]): List of input sources
        predictions (list[str]): List of output sources
        labels (list[list[str]]): List of list of reference strings
    Returns:
        dict: Output of computed metrics

    """
    assert type(sources) == list and type(sources[0]) == str, print(
        "Sources should be a list of strings"
    )
    assert type(predictions) == list and type(predictions[0]) == str, print(
        "Predictions should be a list of strings"
    )
    assert type(labels) == list and type(labels[0]) == list, print(
        "Labels should be a list of LISTS, each containing the labels"
    )

    # Clean inputs
    sources = [clean_string(s) for s in sources]
    predictions = [clean_string(s) for s in predictions]
    labels = [[clean_string(s) for s in lst] for lst in labels]

    result = dict[str, float | list[float]]()

    if "rouge" in metrics:
        result_rouge: Mapping[str, float] = calculate_rouge(predictions, labels)
        for key in result_rouge.keys():
            result[key] = float(result_rouge[key])

    if "sari" in metrics:
        result_sari = calculate_sari(
            sources=sources, predictions=predictions, references=labels
        )
        result["sari"] = result_sari

    if "bert_score" in metrics:
        result["bert_score"] = calculate_bertscore(
            predictions=predictions, references=labels
        )

    if "bert_score_l" in metrics:
        result["bert_score_l"] = calculate_bertscore(
            predictions=predictions, references=[[item] for item in sources]
        )

    if "bleu" in metrics:
        result["bleu"] = calculate_bleu(predictions=predictions, references=labels)

    if "bleu_indiv" in metrics:
        result["bleu_indiv"] = [
            calculate_bleu(predictions=[p], references=[lst])
            for (p, lst) in zip(predictions, labels)
        ]

    if "chrf" in metrics:
        result["chrf"] = calculate_chrf(predictions=predictions, references=labels)

    if "chrf_indiv" in metrics:
        result["chrf_indiv"] = [
            calculate_chrf(predictions=[p], references=[lst])
            for (p, lst) in zip(predictions, labels)
        ]

    if "meteor" in metrics:
        result["meteor"] = calculate_meteor(predictions=predictions, references=labels)

    if "f1" in metrics:
        result["f1"] = calculate_f1(predictions=predictions, references=labels)

    if "f1_indiv" in metrics:
        result["f1_indiv"] = [
            calculate_f1_indiv(p, lst[0]) for (p, lst) in zip(predictions, labels)
        ]

    if "exact_match_gsm8k" in metrics:
        result["exact_match_gsm8k"] = calculate_exact_match_gsm8k(
            predictions=predictions, references=labels
        )

    if "exact_match_math" in metrics:
        result["exact_match_math"] = calculate_exact_match_math(
            predictions=predictions, references=labels
        )
    return result
